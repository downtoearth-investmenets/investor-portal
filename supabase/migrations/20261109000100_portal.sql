-- Database owner runs this migration. Runtime logins are granted one role each.
CREATE SCHEMA portal_users;
CREATE SCHEMA portal_loans;
REVOKE ALL ON SCHEMA portal_users, portal_loans FROM PUBLIC;

-- The application uses direct database connections, never the Supabase Data API.
DO $portal$
DECLARE api_role text;
BEGIN
  FOR api_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated', 'service_role')
  LOOP
    EXECUTE format('REVOKE ALL ON SCHEMA portal_users, portal_loans FROM %I', api_role);
  END LOOP;
END;
$portal$;

CREATE ROLE portal_users_runtime NOLOGIN;
CREATE ROLE portal_loans_runtime NOLOGIN;
GRANT USAGE ON SCHEMA portal_users TO portal_users_runtime;
GRANT USAGE ON SCHEMA portal_loans TO portal_loans_runtime;

CREATE TABLE portal_users.users (
  id text PRIMARY KEY,
  email text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'investor')),
  full_name text NOT NULL,
  phone text NOT NULL DEFAULT '',
  status text NOT NULL CHECK (status IN ('active', 'invited', 'disabled')),
  password_hash text,
  password_changed_at timestamptz,
  created_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX users_email_case_insensitive ON portal_users.users (lower(email));

CREATE TABLE portal_users.investor_profiles (
  id text PRIMARY KEY,
  user_id text NOT NULL UNIQUE REFERENCES portal_users.users(id) ON DELETE CASCADE,
  entity_name text NOT NULL DEFAULT '',
  accredited smallint NOT NULL DEFAULT 0 CHECK (accredited IN (0, 1)),
  created_at timestamptz NOT NULL
);

CREATE TABLE portal_users.sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES portal_users.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL,
  expires_at bigint NOT NULL
);
CREATE INDEX sessions_user ON portal_users.sessions(user_id);
CREATE INDEX sessions_expiration ON portal_users.sessions(expires_at);

CREATE TABLE portal_users.auth_tokens (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES portal_users.users(id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('invite', 'reset')),
  expires_at bigint NOT NULL,
  used_at timestamptz,
  created_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX auth_tokens_one_open_link
  ON portal_users.auth_tokens(user_id, purpose) WHERE used_at IS NULL;

CREATE TABLE portal_users.email_outbox (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  to_email text NOT NULL,
  subject text NOT NULL,
  body text NOT NULL,
  delivered_via text NOT NULL,
  created_at timestamptz NOT NULL
);

CREATE TABLE portal_loans.loans (
  id text PRIMARY KEY,
  loan_number text NOT NULL UNIQUE,
  borrower_name text NOT NULL,
  borrower_contact text NOT NULL DEFAULT '',
  principal_amount numeric(16,2) NOT NULL CHECK (principal_amount > 0),
  term_months integer NOT NULL CHECK (term_months BETWEEN 1 AND 360),
  origination_date date NOT NULL,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'pending', 'paid_off')),
  investor_id text NOT NULL REFERENCES portal_users.investor_profiles(id),
  investor_name text NOT NULL DEFAULT '',
  property jsonb NOT NULL CHECK (jsonb_typeof(property) = 'object'),
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL
);
CREATE INDEX loans_investor ON portal_loans.loans(investor_id);

CREATE TABLE portal_loans.rate_changes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id text NOT NULL REFERENCES portal_loans.loans(id) ON DELETE CASCADE,
  rate numeric(9,6) NOT NULL CHECK (rate BETWEEN 1 AND 30),
  effective_date date NOT NULL,
  reason text NOT NULL,
  changed_by text NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE INDEX rate_changes_by_loan ON portal_loans.rate_changes(loan_id, effective_date, id);

CREATE TABLE portal_loans.payments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id text NOT NULL REFERENCES portal_loans.loans(id) ON DELETE CASCADE,
  installment_number integer NOT NULL CHECK (installment_number BETWEEN 1 AND 360),
  amount numeric(16,2) NOT NULL CHECK (amount > 0),
  received_date date NOT NULL,
  method text NOT NULL CHECK (method IN ('ACH', 'Check', 'Wire', 'Other')),
  reference text NOT NULL DEFAULT '',
  recorded_by text NOT NULL,
  created_at timestamptz NOT NULL,
  UNIQUE (loan_id, installment_number)
);

CREATE TABLE portal_loans.activity (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id text NOT NULL REFERENCES portal_loans.loans(id) ON DELETE CASCADE,
  kind text NOT NULL,
  message text NOT NULL,
  actor text NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE INDEX activity_by_loan ON portal_loans.activity(loan_id, id DESC);

GRANT SELECT, INSERT, UPDATE ON portal_users.users, portal_users.investor_profiles TO portal_users_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON portal_users.sessions, portal_users.auth_tokens TO portal_users_runtime;
GRANT INSERT ON portal_users.email_outbox TO portal_users_runtime;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA portal_users TO portal_users_runtime;

GRANT SELECT, INSERT, UPDATE ON portal_loans.loans TO portal_loans_runtime;
GRANT SELECT, INSERT ON portal_loans.rate_changes, portal_loans.activity TO portal_loans_runtime;
GRANT SELECT, INSERT, DELETE ON portal_loans.payments TO portal_loans_runtime;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA portal_loans TO portal_loans_runtime;
